async function importGenerated(file: string, name: string, category: string, tags: string[]) {
  return importAsset({ sourcePath: file, originalName: name, category, projectId: null, provenance: { source: 'demo', license: DEMO_LICENSE }, tags, move: true });
}

async function png(svgText: string, name: string, category: string, tags: string[]) {
  const f = tmpFile('.png');
  await rasterize(svgText, f);
  return importGenerated(f, name, category, tags);
}

/** Build the shared demo library (idempotent): 3 characters, 4 environments (+1 lighting variant), music, ambience, SFX. */
export async function ensureDemoLibrary(log: (m: string) => void = () => {}) {
  const db = getDb();
  const existing = db.select().from(schema.characters).where(eq(schema.characters.name, 'Miko')).get();
  if (existing?.locked) {
    log('Demo library already present');
    return;
  }
  const series = db.select().from(schema.series).where(eq(schema.series.name, 'Hillmoor Tales')).get();
  const seriesId = series?.id ?? `ser_hillmoor`;
  if (!series) db.insert(schema.series).values({ id: seriesId, name: 'Hillmoor Tales', description: 'Cozy adventures in a lantern-lit hill town (SceneForge demo series).' }).run();

  for (const d of DEMO_CHARACTERS) {
    const info = NAMES[d.key];
    log(`Character art: ${info.name}`);
    const useEspeak = defaultTtsModel() === 'local/espeak-ng';
    const c = createCharacter({
      name: info.name,
      description: info.description,
      personality: info.personality,
      palette: [d.hair, d.skin, d.top, d.inner, d.pants, d.accent],
      proportions: info.proportions,
      identifyingDetails: info.details,
      seriesId,
      voiceProvider: 'auto',
      voiceId: useEspeak ? info.voice : info.mock,
    });
    const tag = (t: string) => [`character:${d.key}`, t];
    for (const pose of ['idle', 'cheer', 'point'] as const) {
      const a = await png(bodySvg(d, pose), `${d.key}-pose-${pose}.png`, 'character', tag(`pose:${pose}`));
      addVariant(c.id, { kind: 'pose', name: pose, assetId: a.id, approved: true });
    }
    for (const ex of ['neutral', 'happy', 'angry', 'sad', 'surprised', 'worried']) {
      const a = await png(faceSvg(d, ex), `${d.key}-face-${ex}.png`, 'character', tag(`expression:${ex}`));
      addVariant(c.id, { kind: 'expression', name: ex, assetId: a.id, approved: true });
    }
    const eyes = await png(eyesClosedSvg(d), `${d.key}-eyes-closed.png`, 'character', tag('eyes:closed'));
    addVariant(c.id, { kind: 'eyes', name: 'closed', assetId: eyes.id, approved: true });
    for (const m of ['closed', 'open', 'wide'] as const) {
      const a = await png(mouthSvg(m), `${d.key}-mouth-${m}.png`, 'character', tag(`mouth:${m}`));
      addVariant(c.id, { kind: 'mouth', name: m, assetId: a.id, approved: true });
    }
    // Full-body reference + expression sheet (reference images for future generation)
    const full = tmpFile('.png');
    const layers = [bodySvg(d, 'idle'), faceSvg(d, 'neutral'), mouthSvg('closed')].map((s) => Buffer.from(s));
    await sharp(layers[0]).composite(layers.slice(1).map((input) => ({ input }))).png().toFile(full);
    const fullA = await importGenerated(full, `${d.key}-fullbody-front.png`, 'character', tag('reference'));
    addVariant(c.id, { kind: 'fullbody', name: 'front', assetId: fullA.id, approved: true });
    const sheetTiles: Buffer[] = [];
    for (const ex of ['neutral', 'happy', 'angry', 'sad', 'surprised', 'worried']) {
      const l = [bodySvg(d, 'idle'), faceSvg(d, ex), mouthSvg(ex === 'happy' || ex === 'surprised' ? 'open' : 'closed')].map((s) => Buffer.from(s));
      const head = await sharp(await sharp(l[0]).composite(l.slice(1).map((input) => ({ input }))).png().toBuffer()).extract({ left: 120, top: 40, width: 360, height: 400 }).png().toBuffer();
      sheetTiles.push(head);
    }
    const sheet = tmpFile('.png');
    await sharp({ create: { width: 360 * 6, height: 400, channels: 4, background: '#f4efe6' } }).composite(sheetTiles.map((input, i) => ({ input, left: i * 360, top: 0 }))).png().toFile(sheet);
    const sheetA = await importGenerated(sheet, `${d.key}-expression-sheet.png`, 'character', tag('sheet'));
    addVariant(c.id, { kind: 'sheet', name: 'expressions', assetId: sheetA.id, approved: true });
    rebuildRig(c.id);
    for (const item of CONTINUITY_ITEMS) setContinuity(c.id, item, true);
    setLocked(c.id, true);
    if (d.key === 'sato') updateCharacter(c.id, { voiceSettings: { speed: 0.95 } });
  }

  for (const e of demoEnvironments()) {
    log(`Environment: ${e.name}`);
    const envId = createEnvironment({ name: e.name, category: e.category, description: '', timeOfDay: e.timeOfDay, backgroundColor: e.backgroundColor, lighting: { tint: null, tintOpacity: 0, ambience: e.weather }, cameraPresets: ['establishing', 'wide', 'medium', 'closeup'] });
    for (const [i, l] of e.layers.entries()) {
      const a = await png(l.svg, `${e.key}-${i}-${l.role}.png`, 'background', [`environment:${e.key}`, `layer:${l.role}`]);
      addLayer(envId, { assetId: a.id, role: l.role, parallax: l.parallax });
    }
    setEnvironmentLocked(envId, true);
    if (e.key === 'street') {
      const v = createLightingVariant(envId, { name: 'Hillmoor Street (Sunset)', timeOfDay: 'sunset', tint: '#ff8a3d', tintOpacity: 0.28 });
      setEnvironmentLocked(v, true);
    }
  }

  log('Music, ambience and SFX');
  const moods: MusicMood[] = ['calm', 'adventurous', 'tense', 'playful'];
  for (const m of moods) {
    const f = tmpFile('.wav');
    writeWav(f, music(32, m, 3));
    await importGenerated(f, `music-${m}.wav`, 'music', [`music:${m}`]);
  }
  for (const k of ['wind', 'rain', 'city', 'night'] as AmbienceKind[]) {
    const f = tmpFile('.wav');
    writeWav(f, ambience(20, k));
    await importGenerated(f, `ambience-${k}.wav`, 'ambience', [`ambience:${k}`]);
  }
  for (const k of ['whoosh', 'impact', 'chime', 'pop', 'steps', 'thunder'] as SfxKind[]) {
    const f = tmpFile('.wav');
    writeWav(f, [sfx(k)]);
    await importGenerated(f, `sfx-${k}.wav`, 'sfx', [`sfx:${k}`]);
  }
}

function assetByTag(tag: string) {
  return getDb()
    .select()
    .from(schema.assets)
    .where(sql`${schema.assets.tags} like ${'%"' + tag + '"%'}`)
    .get();
}

/**
 * Create the demo project and drive it through every checkpoint up to (and including) final-review readiness.
 * Uses ONLY mock and free local providers. Generation approvals are recorded explicitly, exactly like the UI.
 */
export async function createDemoProject(log: (m: string) => void = () => {}) {
  registerHandlers();
  await ensureDemoLibrary(log);
  const db = getDb();
  const series = db.select().from(schema.series).where(eq(schema.series.name, 'Hillmoor Tales')).get()!;
  const project = createProject({ title: 'The Lantern Courier', presetId: 'adventure', aspect: '16:9', targetDurationSec: 120, seriesId: series.id, sourceKind: 'script', sourceInput: DEMO_SCRIPT, budgetLimitUsd: 25 });
  log(`Project ${project.id}`);
  applyStoryDraft(project.id, parseScript(DEMO_SCRIPT));
  approveCheckpoint(project.id, 'story', 'Demo: script and scene breakdown approved');
  approveCheckpoint(project.id, 'art', 'Demo: locked characters, environments and style approved');

  planShots(project.id);
  // Director tweaks (what a user would do in the storyboard editor)
  const shots = listShots(project.id);
  const story = getStory(project.id);
  const lastScene = story.scenes[story.scenes.length - 1];
  for (const s of shots) {
    if (s.sceneId === lastScene.id && /bursts into light/.test(s.purpose)) {
      updateShot(s.id, {
        mode: 'A',
        characters: s.characters.map((c) => ({ ...c, pose: 'cheer', expression: 'happy', moveToX: null, enterFrom: 'none' })),
        effects: { ...s.effects, weather: 'sparkles', impacts: [0.2], speedLines: false },
        camera: { ...s.camera, move: 'pull-out' },
      });
    }
    if (/Storm Bridge/.test(s.purpose) || (s.sceneId === story.scenes[2].id && s.camera.framing === 'establishing')) {
      updateShot(s.id, { sfx: [{ assetId: assetByTag('sfx:thunder')!.id, at: 0.3, volume: 0.9 }] });
    }
  }
  // storyboard frames (local job)
  createJob({ projectId: project.id, kind: 'storyboard_frames', input: {}, variant: Date.now() });
  await drain('demo');
  approveCheckpoint(project.id, 'storyboard', 'Demo: shot structure + estimated cost approved');

  // Voices (free: local eSpeak NG if installed, else mock babble)
  log(`Generating dialogue with ${defaultTtsModel()}`);
  requestDialogueAudio(project.id);
  await drain('demo', 300_000);

  // Mode B / C shots: start image → approve → (B) image-to-video → approve. Mock provider, simulated cost.
  const aiShots = listShots(project.id).filter((s) => s.mode === 'B' || s.mode === 'C');
  const imgJobs = aiShots.map((s) => requestStartImage(s.id).job.id);
  if (imgJobs.length) {
    const r = approveJobs(project.id, imgJobs, 'Demo: approve mock start images');
    log(`Approved ${imgJobs.length} start-image jobs (simulated $${r.totalUsd})`);
  }
  await drain('demo');
  for (const s of listShots(project.id).filter((x) => x.mode === 'B' || x.mode === 'C')) {
    const v = s.versions.find((x) => x.kind === 'start_image' && x.id === s.startImageVersionId);
    if (v) setVersionStatus(v.id, 'approved');
    const still = s.versions.find((x) => x.kind === 'still');
    if (still) setVersionStatus(still.id, 'approved');
  }
  const vidJobs = listShots(project.id)
    .filter((s) => s.mode === 'B')
    .map((s) => requestShotVideo(s.id).job.id);
  if (vidJobs.length) {
    const r = approveJobs(project.id, vidJobs, 'Demo: approve mock image-to-video clips');
    log(`Approved ${vidJobs.length} video jobs (simulated $${r.totalUsd})`);
  }
  await drain('demo', 300_000);
  for (const s of listShots(project.id).filter((x) => x.mode === 'B')) {
    if (s.activeVersionId) setVersionStatus(s.activeVersionId, 'approved');
  }
  const failed = listJobs({ projectId: project.id, states: ['FAILED', 'NEEDS_RECONCILIATION'] });
  if (failed.length) throw new Error(`Demo jobs failed: ${failed.map((j) => `${j.kind}:${j.error}`).join('; ')}`);

  // Sound design: per-scene music + ambience
  const scenes = getStory(project.id).scenes;
  const per: [string, string][] = [
    ['music:calm', 'ambience:wind'],
    ['music:adventurous', 'ambience:city'],
    ['music:tense', 'ambience:rain'],
    ['music:playful', 'ambience:night'],
  ];
  scenes.forEach((s, i) => {
    const [m, a] = per[i % per.length];
    db.update(schema.scenes).set({ music: assetByTag(m)!.id, ambience: assetByTag(a)!.id }).where(eq(schema.scenes.id, s.id)).run();
  });
  updateEditorSettings(project.id, { musicAssetId: assetByTag('music:adventurous')!.id });
  const tl = saveTimeline(project.id);
  log(`Timeline v${tl.version}: ${(tl.data.durationInFrames / tl.data.fps).toFixed(1)}s, ${tl.data.clips.length} shots`);
  return { projectId: project.id, timelineId: tl.id, durationSec: tl.data.durationInFrames / tl.data.fps };
}

export function demoExists() {
  return fs.existsSync('.') && !!getDb().select().from(schema.projects).where(eq(schema.projects.title, 'The Lantern Courier')).get();
}
